// Builds worker/knowledge.generated.mjs: the facts the AI assistant may rely on, taken from the
// site's own texts (src/i18n/dict.ts, French) and its contact details (src/content/site.ts).
// Run after changing the FAQ, services, process or contact details, then redeploy the Worker:
//   npm run knowledge          writes the file
//   npm run knowledge -- --check   exits 1 if the file is out of date (for CI or a quick look)

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "worker", "knowledge.generated.mjs");

process.removeAllListeners("warning"); // Node warns that dict.ts has no "type": "module"
const { dict } = await import(pathToFileURL(join(root, "src", "i18n", "dict.ts")).href);
const fr = dict.fr;

const site = readFileSync(join(root, "src", "content", "site.ts"), "utf8");
const field = (name) => {
  const m = site.match(new RegExp(`${name}:\\s*"([^"]+)"`));
  if (!m) throw new Error(`contact.${name} not found in src/content/site.ts`);
  return m[1];
};
const contact = {
  whatsapp: field("whatsapp"),
  whatsappLabel: field("whatsappLabel"),
  email: field("email"),
  instagram: field("instagram"),
  tiktok: field("tiktok"),
};

const bullets = (list) => list.map((x) => (/^\d+\. /.test(x) ? x : `- ${x}`)).join("\n");
const w = fr.webPage;

const knowledge = `EGC Studio : studio créatif basé à Abidjan (Côte d'Ivoire), fondé par Egu, freelance. "Production audiovisuelle et marketing digital".
Quatre métiers :
${bullets(fr.disciplines.items.map((i) => `${i.name} : ${i.text}`))}

Ce que fait Egu :
${bullets(fr.about.services)}

L'histoire d'Egu :
${fr.about.bio.join("\n")}

Comment se passe une collaboration (photo et vidéo) :
${bullets(fr.process.steps.map((s, i) => `${i + 1}. ${s.title} : ${s.text}`))}

Sites web (réalisés par l'équipe web du studio, pilotée par Egu) :
${w.intro}
Ce que le studio crée :
${bullets(w.offers.map((o) => `${o.name} : ${o.text}`))}
Dans chaque site :
${bullets(w.included)}
Étapes d'un site :
${bullets(w.process.map((s, i) => `${i + 1}. ${s.title} : ${s.text}`))}
Questions fréquentes sur les sites :
${bullets(w.faq.map((f) => `${f.q} ${f.a}`))}

Types de projets proposés dans la demande guidée :
${bullets(Object.entries(fr.assistant.kinds).map(([k, v]) => `${k} : ${v.join(", ")}`))}

Questions fréquentes :
${bullets(fr.assistant.faq.map((f) => `${f.q} ${f.a}`))}

Le site : pages Travaux (photos et créations graphiques), Films, Web, À propos, Contact. Il existe en français et en anglais (bouton FR / EN). La section "Offres et tarifs" de la page d'accueil montre les affiches de tarifs d'Egu : renvoyer le visiteur vers cette section, sans jamais citer de montant.
Contact : WhatsApp ${contact.whatsappLabel}, e-mail ${contact.email}, Instagram @${contact.instagram}, TikTok @${contact.tiktok}. Egu répond sous 24 heures.`;

const file = `// Generated by scripts/make-knowledge.mjs from src/i18n/dict.ts and src/content/site.ts. Do not edit by hand.
export const CONTACT = ${JSON.stringify(contact, null, 2)};

export const KNOWLEDGE_FR = ${JSON.stringify(knowledge)};
`;

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (current !== file) {
    console.error("worker/knowledge.generated.mjs is out of date: run `npm run knowledge`, then redeploy the Worker.");
    process.exit(1);
  }
  console.log("worker/knowledge.generated.mjs is up to date.");
} else {
  writeFileSync(out, file);
  console.log(`Wrote ${out} (${knowledge.length} characters of knowledge).`);
}
